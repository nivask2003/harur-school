<script>
document.addEventListener('DOMContentLoaded', function () {
    const itemsPerSlide = 4; // how many boxes show at once on desktop (see CSS breakpoints)
    const carouselEl = document.querySelector('#academicsCarousel');
    if (!carouselEl) return;

    const items = carouselEl.querySelectorAll('.carousel-item');

    items.forEach((el) => {
        let next = el.nextElementSibling;
        for (let i = 1; i < itemsPerSlide; i++) {
            if (!next) {
                next = items[0];
            }
            const cloneChild = next.cloneNode(true);
            el.appendChild(cloneChild.children[0]);
            next = next.nextElementSibling;
        }
    });

    new bootstrap.Carousel(carouselEl, {
        interval: 3000,   // autoplay every 3s — change as needed
        ride: 'carousel',
        wrap: true,
        pause: 'hover'    // pauses autoplay while hovering, resumes on mouse-out
    });
});
</script>